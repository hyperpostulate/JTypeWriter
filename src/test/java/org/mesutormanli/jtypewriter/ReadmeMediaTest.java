package org.mesutormanli.jtypewriter;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import org.junit.jupiter.api.Test;

/**
 * Keeps the README's screenshots real: present, paired by language, described,
 * and small enough that the document stays readable on the connection a first
 * visitor actually has.
 *
 * <p>A broken image tag is invisible in a diff and obvious on the rendered
 * page, so nothing failed when one pointed at a path that had been moved; and
 * an oversized recording would be committed once and serve every visitor for
 * the life of the repository. Both are the same class of defect the other
 * documentation tests exist for - a hand-maintained promise that no build
 * checks - so the reference set, the file on disk and the byte count are all
 * verified here.</p>
 *
 * <p>The media is generated by {@code scripts/capture-hero-gif.sh}: the
 * animation is a recording of the packaged application, not a mock-up, and the
 * script is what makes it reproducible after a toolbar change. That is why the
 * script itself is checked for the two output paths - a README pointing at
 * files no command can produce is a claim nothing can back up.</p>
 *
 * <p>Headless and read-only: two documents, one directory, no toolkit, no
 * network, no writes.</p>
 */
class ReadmeMediaTest {

    private static final Path EN = Path.of("README.md");
    private static final Path TR = Path.of("README-TR.md");
    private static final Path MEDIA_DIR = Path.of("docs", "media");
    private static final Path ICON_DIR = Path.of("src", "main", "resources", "icons");
    private static final Path CAPTURE_SCRIPT = Path.of("scripts", "capture-hero-gif.sh");

    /** A Markdown or HTML reference into the media directory. */
    private static final Pattern MEDIA_REFERENCE = Pattern.compile("docs/media/([A-Za-z0-9._-]+)");
    /** An {@code <img src>} pointing into the media directory. */
    private static final Pattern IMAGE_SOURCE =
            Pattern.compile("<img\\b[^>]*src=\"docs/media/([A-Za-z0-9._-]+)\"");
    private static final Pattern IMAGE_TAG = Pattern.compile("<img\\b[^>]*>");

    /**
     * Two megabytes is generous for ten seconds of a mostly flat dark theme at
     * 900 px; it is a ceiling, not a target. The current recordings are well
     * under it, and the capture script fails its own run above 3 MiB, so a
     * committed file that grows past this means the encoder settings moved.
     */
    private static final long MAX_GIF_BYTES = 2L * 1024 * 1024;

    @Test
    void everyMediaReferenceNamesAFileThatExistsAndIsNotEmpty() throws IOException {
        for (var readme : List.of(EN, TR)) {
            var missing = new ArrayList<String>();
            for (var name : referencedMedia(readme)) {
                var file = MEDIA_DIR.resolve(name);
                if (!Files.isRegularFile(file) || Files.size(file) == 0) {
                    missing.add(name);
                }
            }
            assertTrue(missing.isEmpty(),
                    readme + " shows screenshots that are not on disk: " + missing
                            + " (regenerate them with " + CAPTURE_SCRIPT + ")");
        }
    }

    /**
     * Each half shows the recording of its own UI language: a Turkish README
     * with an English toolbar shows a Turkish reader a product that does not
     * look like theirs, which is the opposite of what a screenshot is for.
     *
     * <p>Only images are compared, not every mention of a path: the prose
     * explains which command produces which file, so both names appear in both
     * documents on purpose.</p>
     */
    @Test
    void eachHalfShowsTheRecordingOfItsOwnLanguage() throws IOException {
        var english = imageSources(EN);
        var turkish = imageSources(TR);
        for (var name : english) {
            assertFalse(name.contains("-tr."),
                    EN + " shows " + name + ", which was recorded in Turkish");
        }
        for (var name : turkish) {
            assertFalse(name.contains("-en."),
                    TR + " shows " + name + ", which was recorded in English");
        }
        assertTrue(english.contains("hero-en.gif"),
                EN + " does not show hero-en.gif");
        assertTrue(turkish.contains("hero-tr.gif"),
                TR + " does not show hero-tr.gif");
    }

    /**
     * A screenshot with no {@code alt} text is a blank rectangle to a screen
     * reader - the one audience a picture is otherwise useless for. Both halves
     * carry their own wording, so the attribute is checked for presence and for
     * not being an empty placeholder.
     */
    @Test
    void everyImageInBothHalvesCarriesAltText() throws IOException {
        for (var readme : List.of(EN, TR)) {
            var text = Files.readString(readme, StandardCharsets.UTF_8);
            var matcher = IMAGE_TAG.matcher(text);
            var undescribed = new ArrayList<String>();
            while (matcher.find()) {
                var tag = matcher.group();
                if (!tag.contains("docs/media/")) {
                    continue;
                }
                var alt = Pattern.compile("alt=\"([^\"]*)\"").matcher(tag);
                if (!alt.find() || alt.group(1).isBlank()) {
                    undescribed.add(tag);
                }
            }
            assertTrue(undescribed.isEmpty(),
                    readme + " has screenshot tags without alt text: " + undescribed);
        }
    }

    /**
     * The recording answers "what does this feel like" while the reader is still
     * deciding, so it sits directly under the opening paragraph - above the
     * feature list, the table of contents and the download instructions.
     */
    @Test
    void theHeroAnimationSitsDirectlyUnderTheOpeningParagraph() throws IOException {
        var english = Files.readString(EN, StandardCharsets.UTF_8);
        var turkish = Files.readString(TR, StandardCharsets.UTF_8);
        int englishHero = english.indexOf("docs/media/hero-en.gif");
        int turkishHero = turkish.indexOf("docs/media/hero-tr.gif");
        assertTrue(englishHero > 0, EN + " does not show hero-en.gif");
        assertTrue(turkishHero > 0, TR + " does not show hero-tr.gif");
        assertTrue(englishHero < english.indexOf("## What you get"),
                EN + " shows the recording after the feature list instead of above it");
        assertTrue(turkishHero < turkish.indexOf("## Neler var?"),
                TR + " shows the recording after the feature list instead of above it");
    }

    /**
     * A recording that is small in bytes can still be enormous on screen, which
     * is what makes a page scroll sideways; the GIF header carries the logical
     * screen size, so it is read without decoding any frames.
     */
    @Test
    void theHeroAnimationIsDocumentSized() throws IOException {
        for (var name : List.of("hero-en.gif", "hero-tr.gif")) {
            var file = MEDIA_DIR.resolve(name);
            var bytes = Files.readAllBytes(file);
            assertTrue(bytes.length > 6 && bytes[0] == 'G' && bytes[1] == 'I' && bytes[2] == 'F',
                    file + " is not a GIF");
            var width = (bytes[6] & 0xff) | ((bytes[7] & 0xff) << 8);
            var height = (bytes[8] & 0xff) | ((bytes[9] & 0xff) << 8);
            assertTrue(width >= 600 && width <= 1200,
                    file + " is " + width + " px wide; the README renders it at 900, so a"
                            + " recording outside that range is resized by the browser and"
                            + " wastes bytes");
            assertTrue(height >= 200 && height <= 900,
                    file + " is " + height + " px tall, which is not a window-shaped recording");
            assertTrue(bytes.length <= MAX_GIF_BYTES,
                    file + " is " + bytes.length + " bytes, over the " + MAX_GIF_BYTES
                            + " byte budget; shrink OUTPUT_WIDTH or shorten the sample text in "
                            + CAPTURE_SCRIPT);
        }
    }

    /**
     * The icons directory has its own contract: {@code generate-icons.py --check}
     * treats a stray image there as a failure, and everything in
     * {@code src/main/resources} is packed into the jar. Document media must
     * stay outside both.
     */
    @Test
    void theDocumentMediaIsNotShippedInsideTheJar() throws IOException {
        try (Stream<Path> files = Files.walk(ICON_DIR)) {
            var strays = files.filter(Files::isRegularFile)
                    .map(path -> path.getFileName().toString())
                    .filter(name -> (name.startsWith("hero-") || name.contains("screenshot")))
                    .toList();
            assertTrue(strays.isEmpty(),
                    ICON_DIR + " holds document media, which would be packed into the jar and"
                            + " rejected by generate-icons.py --check: " + strays);
        }
    }

    /**
     * The script is the only supported way to produce these files, and it must
     * keep producing exactly the names the READMEs reference - otherwise the
     * next person reruns it and quietly gets a different document.
     */
    @Test
    void theCaptureScriptProducesTheFilesTheReadmesShow() throws IOException {
        assertTrue(Files.isRegularFile(CAPTURE_SCRIPT),
                CAPTURE_SCRIPT + " is missing; the screenshots would have no reproducible source");
        var script = Files.readString(CAPTURE_SCRIPT, StandardCharsets.UTF_8);
        assertTrue(script.contains("OUT_DIR=\"docs/media\""), CAPTURE_SCRIPT
                + " does not write into docs/media, which is where the READMEs look");
        for (var language : List.of("en", "tr")) {
            assertTrue(script.contains("[en]") && script.contains("[tr]"),
                    CAPTURE_SCRIPT + " does not declare both language samples");
            assertTrue(script.contains("hero-$language.gif"),
                    CAPTURE_SCRIPT + " does not name its output hero-<language>.gif, so the"
                            + " README's hero-" + language + ".gif has no producer");
        }
        assertTrue(script.contains("releases/linux/JTypeWriter/bin/JTypeWriter"),
                CAPTURE_SCRIPT + " does not record the packaged application, so the"
                        + " screenshots would show a developer's build instead of the artifact");
        assertTrue(script.contains("JAVA_TOOL_OPTIONS=-Duser.home"),
                CAPTURE_SCRIPT + " does not isolate user.home, so it would read and write the"
                        + " real ~/.jtypewriter");
    }

    /** Every {@code docs/media/...} file name a document mentions, in order. */
    private static Set<String> referencedMedia(Path readme) throws IOException {
        var text = Files.readString(readme, StandardCharsets.UTF_8);
        var names = new LinkedHashSet<String>();
        var matcher = MEDIA_REFERENCE.matcher(text);
        while (matcher.find()) {
            names.add(matcher.group(1));
        }
        return names;
    }

    /** The media files a document actually displays, as opposed to mentions. */
    private static Set<String> imageSources(Path readme) throws IOException {
        var text = Files.readString(readme, StandardCharsets.UTF_8);
        var names = new LinkedHashSet<String>();
        var matcher = IMAGE_SOURCE.matcher(text);
        while (matcher.find()) {
            names.add(matcher.group(1));
        }
        return names;
    }
}
