#!/usr/bin/env python3
"""Regenerate the bundled application icons from the canonical SVG.

The artwork has exactly one source, ``src/main/resources/icons/jtypewriter.svg``.
This script renders the PNG sizes and the Windows ``.ico`` from it, and records
the result in ``icons.manifest`` so the committed binaries can always be traced
back to that file.

Usage:
    scripts/generate-icons.py               # regenerate assets + manifest
    scripts/generate-icons.py --check       # fail if the assets drifted from the manifest
    scripts/generate-icons.py --render      # also re-rasterise and compare pixels

Requires ImageMagick for rasterising the SVG - the ImageMagick 7 ``magick``
driver, or the legacy ``convert``/``compare`` of version 6 when that is what the
machine has; everything else is plain Python. ``--check`` needs no ImageMagick at
all, which is why it is the form CI runs.

``--check`` verifies hashes, not pixels, and the distinction is deliberate: a
PNG's bytes are an encoding of its pixels, and every ImageMagick build carries a
slightly different zlib and filter heuristic, so the same artwork produced on a
developer machine and on a CI runner encodes to different files while showing the
same picture. Byte equality across machines would therefore reject a correct
asset set, and a pixel comparison would only be as stable as the least stable
rasteriser version. The manifest records what was generated from which SVG, so
the one failure that matters - the artwork changed and nobody re-ran this script
- is caught on every machine, with no tolerance to tune.

``--render`` is the stronger, machine-local proof (re-render from the SVG and
compare pixels against the committed assets, 0.0 being identical). Run it after
regenerating; it is documented rather than automated because its result depends
on the rasteriser and encoder installed.

The SVG deliberately avoids gradients and filters because ImageMagick's internal
MSVG renderer paints gradient fills as solid black. Render with
``-background none`` so the corners stay transparent (a plain ``magick in.svg
out.png`` floods them with black).
"""

from __future__ import annotations

import argparse
import hashlib
import io
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ICON_DIR = ROOT / "src" / "main" / "resources" / "icons"
SVG = ICON_DIR / "jtypewriter.svg"
ICO = ICON_DIR / "jtypewriter.ico"
MANIFEST = ICON_DIR / "icons.manifest"

# PNG sizes kept in the repository. 16/24/32 feed JavaFX and Windows trays,
# 64..512 the launchers and package icons, 1024 the source for the downscales.
PNG_SIZES = (16, 24, 32, 48, 64, 128, 256, 512, 1024)

# ICO entries: (size, chunk id). Modern Windows (and jpackage, which needs 10+)
# reads PNG-compressed entries at any size, so the .ico stays small.
ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)

RENDER_DENSITY = "384"

# Allowed normalised RMSE between a re-render and the committed asset for
# ``--render``: 0.0 is a pixel-identical image, 1.0 an unrelated one. A different
# encoder still scores 0.00 (the same pixels, compressed differently), while
# unrelated artwork scores in the tens of percent; a recoloured shape stays well
# above this line.
RENDER_TOLERANCE = 0.002

MANIFEST_HEADER = """\
# Generated by scripts/generate-icons.py - do not edit by hand.
#
# Every icon under this directory is rasterised from jtypewriter.svg, and this
# file records the bytes that render produced, including the SVG's own hash.
# The point is a machine-independent staleness check: a PNG re-encodes
# differently on every ImageMagick build, so comparing bytes across machines
# would fail on correct assets, while comparing hashes pinned at generation
# time fails exactly when the artwork changed and nobody regenerated it.
#
# Regenerate with: scripts/generate-icons.py
"""


class CompareError(Exception):
    """ImageMagick could not diff the two files (wrong size, corrupt PNG...)."""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def magick() -> list[str]:
    """The ImageMagick command, as a prefix: ``magick`` (v7) or ``convert`` (v6).

    Every operation here is a single-image read-modify-write, so the two
    drivers are interchangeable for these flags and the choice is purely
    "which one this machine installed".
    """
    for candidate in (["magick"], ["convert"]):
        if shutil.which(candidate[0]):
            return candidate
    sys.exit("ImageMagick ('magick' or 'convert') is required to rasterise the SVG")


def compare_command() -> list[str]:
    """The ImageMagick diff command, as a prefix: ``magick compare`` or ``compare``."""
    if shutil.which("magick"):
        return ["magick", "compare"]
    if shutil.which("compare"):
        return ["compare"]
    sys.exit("ImageMagick ('magick compare' or 'compare') is required to compare the assets")


def run(command: list[str]) -> None:
    subprocess.run(command, check=True)


def manifest_text(files: dict[str, bytes]) -> str:
    """The manifest body: one ``<sha256>  <name>`` line per generated file."""
    lines = [MANIFEST_HEADER]
    for name in ["jtypewriter.svg", *[f"jtypewriter-{s}.png" for s in PNG_SIZES], "jtypewriter.ico"]:
        lines.append(f"{sha256(files[name])}  {name}\n")
    return "".join(lines)


def read_manifest() -> dict[str, str]:
    """{name: sha256} from the committed manifest; raises ValueError when unusable."""
    if not MANIFEST.is_file():
        raise ValueError(f"{MANIFEST.name} is missing")
    entries: dict[str, str] = {}
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        digest, _, name = line.partition("  ")
        if len(digest) != 64 or not name:
            raise ValueError(f"{MANIFEST.name} has a malformed line: {line!r}")
        entries[name] = digest
    return entries


def expected_names() -> list[str]:
    return ["jtypewriter.svg", *[f"jtypewriter-{s}.png" for s in PNG_SIZES], "jtypewriter.ico"]


def check_manifest() -> list[str]:
    """Every asset whose bytes are not the ones the manifest records."""
    try:
        entries = read_manifest()
    except ValueError as error:
        return [f"{MANIFEST.name}  ({error})"]

    problems: list[str] = []
    for name in expected_names():
        if name not in entries:
            problems.append(f"{name}  (not listed in {MANIFEST.name})")
            continue
        path = ICON_DIR / name
        if not path.is_file():
            problems.append(f"{name}  (missing)")
            continue
        actual = sha256(path.read_bytes())
        if actual != entries[name]:
            problems.append(f"{name}  (changed since the manifest was written)")
    for name in sorted(entries):
        if name not in expected_names():
            problems.append(f"{name}  (listed in {MANIFEST.name} but not a generated asset)")
    # A file this script never produced is a stale leftover: an icon at a size
    # nobody ships still gets packaged into the jar and handed to jpackage.
    for path in sorted(ICON_DIR.iterdir()):
        if path.is_file() and path.suffix.lower() in {".png", ".ico"} \
                and path.name not in expected_names():
            problems.append(f"{path.name}  (in the icon directory but not produced by this"
                            " script)")
    return problems


def deviation(rendered: Path, committed: Path) -> float:
    """Normalised RMSE between two images: 0.0 identical, 1.0 unrelated.

    ImageMagick writes the metric to stderr as ``<absolute> (<normalised>)`` and
    exits 1 when the images differ, so a non-zero status is not an error here -
    only an unparsable one, or a failure to read either file, is.
    """
    proc = subprocess.run(
        [*compare_command(), "-metric", "RMSE", str(rendered), str(committed), "null:"],
        capture_output=True,
        text=True,
    )
    match = re.search(r"\(([-+0-9.eE]+)\)", proc.stderr or "")
    if proc.returncode > 1 or match is None:
        message = (proc.stderr or proc.stdout or "").strip().splitlines()
        raise CompareError(message[-1] if message else f"exit {proc.returncode}")
    return float(match.group(1))


def render_base(workdir: Path) -> Path:
    """Rasterise the SVG once at 1024 px, then downscale from that master.

    Rendering every size from the SVG directly would pay the (slow) MSVG parse
    cost seven times and give noticeably different stroke weights per size.
    """
    base = workdir / "base-1024.png"
    run([
        *magick(),
        "-background", "none",
        "-density", RENDER_DENSITY,
        str(SVG),
        "-resize", "1024x1024",
        "-strip",
        "PNG32:" + str(base),
    ])
    if not base.is_file():
        sys.exit("ImageMagick did not produce " + str(base))
    return base


def render_png(base: Path, size: int, target: Path) -> None:
    run([
        *magick(), str(base),
        "-filter", "Lanczos",
        "-resize", f"{size}x{size}",
        "-strip",
        "PNG32:" + str(target),
    ])


def build_ico(pngs: dict[int, bytes]) -> bytes:
    """PNG-compressed .ico (Vista+); every entry keeps its own alpha."""
    count = len(ICO_SIZES)
    header = struct.pack("<HHH", 0, 1, count)  # reserved, type=icon, count
    entries = bytearray()
    payload = bytearray()
    offset = len(header) + 16 * count
    for size in ICO_SIZES:
        data = pngs[size]
        entries += struct.pack(
            "<BBBBHHII",
            size if size < 256 else 0,  # 256 is encoded as 0
            size if size < 256 else 0,
            0,  # palette size
            0,  # reserved
            1,  # colour planes
            32,  # bits per pixel
            len(data),
            offset + len(payload),
        )
        payload += data
    return bytes(header + entries + payload)


def parse_ico(data: bytes) -> dict[int, bytes]:
    """Split an .ico back into {size: PNG payload}, for ``--render`` to read."""
    if len(data) < 6:
        raise CompareError("file is shorter than an icon header")
    reserved, kind, count = struct.unpack_from("<HHH", data, 0)
    if reserved != 0 or kind != 1:
        raise CompareError("not an icon file (bad header)")
    entries: dict[int, bytes] = {}
    for index in range(count):
        fields = struct.unpack_from("<BBBBHHII", data, 6 + 16 * index)
        width, _height, _palette, _reserved, _planes, _bits, length, offset = fields
        size = 256 if width == 0 else width
        payload = data[offset:offset + length]
        if len(payload) != length:
            raise CompareError(f"entry {size} is truncated")
        entries[size] = payload
    return entries


def generate(workdir: Path) -> tuple[dict[Path, bytes], dict[int, Path]]:
    """Render every asset, without writing anything into the repository.

    Returns the bytes to write ({path: bytes}, manifest included) and the
    rendered master per size, which ``--render`` needs as the reference side of
    the pixel comparison.
    """
    outputs: dict[Path, bytes] = {}
    rendered: dict[int, Path] = {}
    base = render_base(workdir)
    pngs: dict[int, bytes] = {}
    for size in PNG_SIZES:
        target = workdir / f"jtypewriter-{size}.png"
        render_png(base, size, target)
        data = target.read_bytes()
        pngs[size] = data
        rendered[size] = target
        outputs[ICON_DIR / target.name] = data
    ico = build_ico(pngs)
    outputs[ICO] = ico
    files = {"jtypewriter.svg": SVG.read_bytes(),
             **{path.name: data for path, data in outputs.items()}}
    outputs[MANIFEST] = manifest_text(files).encode("utf-8")
    return outputs, rendered


def check_render(rendered: dict[int, Path], tolerance: float) -> list[str]:
    """Assets that do not match a fresh render on this machine, pixel for pixel.

    The PNGs are compared against the render of the same size; the .ico twice -
    once structurally (rebuilt from its own payloads, which must reproduce the
    committed bytes exactly, pinning entry order, offsets and metadata) and once
    per entry against the render of that size.
    """
    problems: list[str] = []
    for size in PNG_SIZES:
        committed = ICON_DIR / f"jtypewriter-{size}.png"
        if not committed.is_file():
            problems.append(f"{committed.name}  (missing)")
            continue
        try:
            drift = deviation(rendered[size], committed)
        except CompareError as error:
            problems.append(f"{committed.name}  (unreadable or the wrong size: {error})")
            continue
        if drift > tolerance:
            problems.append(f"{committed.name}  ({drift:.2%} pixel difference, over the"
                            f" {tolerance:.2%} tolerance)")

    if not ICO.is_file():
        problems.append(f"{ICO.name}  (missing)")
        return problems
    try:
        entries = parse_ico(ICO.read_bytes())
    except CompareError as error:
        problems.append(f"{ICO.name}  ({error})")
        return problems
    if set(entries) != set(ICO_SIZES):
        problems.append(f"{ICO.name}  (entries {sorted(entries)}, expected {list(ICO_SIZES)})")
        return problems
    if build_ico(entries) != ICO.read_bytes():
        problems.append(f"{ICO.name}  (entry metadata or ordering does not match the layout"
                        " this script writes)")
        return problems

    with tempfile.TemporaryDirectory(prefix="jtw-ico-") as tmp:
        for size in ICO_SIZES:
            payload = Path(tmp) / f"ico-{size}.png"
            payload.write_bytes(entries[size])
            try:
                drift = deviation(rendered[size], payload)
            except CompareError as error:
                problems.append(f"{ICO.name}  (entry {size} is unreadable: {error})")
                continue
            if drift > tolerance:
                problems.append(f"{ICO.name}  (entry {size}: {drift:.2%} pixel difference,"
                                f" over the {tolerance:.2%} tolerance)")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed assets still match icons.manifest",
    )
    parser.add_argument(
        "--render",
        action="store_true",
        help="re-rasterise the SVG and compare the result with the committed assets",
    )
    parser.add_argument(
        "--tolerance",
        type=float,
        default=RENDER_TOLERANCE,
        metavar="RMSE",
        help=f"allowed normalised RMSE for --render (default {RENDER_TOLERANCE})",
    )
    args = parser.parse_args()

    if not SVG.is_file():
        sys.exit(f"canonical artwork missing: {SVG}")

    if args.check or args.render:
        problems = check_manifest() if args.check else []
        rendered: dict[int, Path] = {}
        if args.render:
            if subprocess.run([*magick(), "-version"], capture_output=True).returncode != 0:
                sys.exit("ImageMagick is required to rasterise the SVG")
            with tempfile.TemporaryDirectory(prefix="jtw-icons-") as tmp:
                _, rendered = generate(Path(tmp))
                problems += check_render(rendered, args.tolerance)
        if problems:
            print("icon assets are out of date, run scripts/generate-icons.py:", file=sys.stderr)
            for line in problems:
                print("  " + line, file=sys.stderr)
            return 1
        if args.render:
            print(f"icon assets match the SVG ({len(expected_names())} files, pixel identical)")
        else:
            print(f"icon assets match {MANIFEST.name} ({len(expected_names())} files)")
        return 0

    if subprocess.run([*magick(), "-version"], capture_output=True).returncode != 0:
        sys.exit("ImageMagick is required to rasterise the SVG")
    with tempfile.TemporaryDirectory(prefix="jtw-icons-") as tmp:
        outputs, _rendered = generate(Path(tmp))
    for path, data in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        with io.open(path, "wb") as handle:
            handle.write(data)
        print(f"wrote {path.relative_to(ROOT)} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
